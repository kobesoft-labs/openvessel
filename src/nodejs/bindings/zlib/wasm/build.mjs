// Builds the brotli and zstd WebAssembly modules used by internalBinding('zlib') and writes them,
// raw-deflated and base64-encoded, to ../brotli-wasm.ts and ../zstd-wasm.ts.
//
// The outputs are committed; run this only to change library versions or build flags:
//   node src/nodejs/bindings/zlib/wasm/build.mjs
// Needs LLVM with the wasm32 target and wasm-ld (Homebrew: `brew install llvm lld`).
// Override with CLANG=/path/to/clang WASM_LD=/path/to/wasm-ld.
//
// Library versions match Node v22.20.0 (process.versions.brotli / process.versions.zstd).

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { deflateRawSync } from 'node:zlib';

const here = new URL('.', import.meta.url).pathname;
const outDir = join(here, '..');
const work = process.env.WORK_DIR ?? join(tmpdir(), 'ov-zlib-wasm');
mkdirSync(work, { recursive: true });

const CLANG = process.env.CLANG ?? '/opt/homebrew/opt/llvm/bin/clang';
const WASM_LD = process.env.WASM_LD ?? (existsSync('/opt/homebrew/bin/wasm-ld') ? '/opt/homebrew/bin/wasm-ld' : 'wasm-ld');

const SOURCES = {
  brotli: {
    version: '1.1.0',
    url: 'https://github.com/google/brotli/archive/refs/tags/v1.1.0.tar.gz',
    sha256: 'e720a6ca29428b803f4ad165371771f5398faba397edf6778837a18599ea13ff',
    dir: 'brotli-1.1.0',
    license: 'MIT',
  },
  zstd: {
    version: '1.5.7',
    url: 'https://github.com/facebook/zstd/releases/download/v1.5.7/zstd-1.5.7.tar.gz',
    sha256: 'eb33e51f49a15e023950cd7825ca74a4a2b43db8354825ac24fc1b7ee09e6fa3',
    dir: 'zstd-1.5.7',
    license: 'BSD-3-Clause',
  },
};

function fetchSource(s) {
  const tgz = join(work, `${s.dir}.tar.gz`);
  if (!existsSync(tgz)) execFileSync('curl', ['-sSfL', '-o', tgz, s.url], { stdio: 'inherit' });
  const sum = createHash('sha256').update(readFileSync(tgz)).digest('hex');
  if (sum !== s.sha256) throw new Error(`${tgz}: sha256 ${sum} != ${s.sha256}`);
  if (!existsSync(join(work, s.dir))) execFileSync('tar', ['xzf', tgz, '-C', work], { stdio: 'inherit' });
  return join(work, s.dir);
}

const cfiles = (dir) => readdirSync(dir).filter((f) => f.endsWith('.c')).map((f) => join(dir, f));

const CFLAGS = [
  '--target=wasm32',
  '-nostdlibinc',
  '-ffreestanding',
  '-fno-builtin-log2',
  '-fno-builtin-log',
  '-mbulk-memory',
  '-msign-ext',
  '-mnontrapping-fptoint',
  '-O2',
  '-DNDEBUG',
  `-I${join(here, 'include')}`,
  '-Wno-everything',
];

function compile(name, srcs, extraFlags) {
  const objDir = join(work, `obj-${name}`);
  mkdirSync(objDir, { recursive: true });
  const objs = [];
  for (const src of srcs) {
    const obj = join(objDir, src.replace(/[\\/]/g, '_') + '.o');
    execFileSync(CLANG, [...CFLAGS, ...extraFlags, '-c', src, '-o', obj], { stdio: 'inherit' });
    objs.push(obj);
  }
  const wasm = join(work, `${name}.wasm`);
  execFileSync(
    WASM_LD,
    [
      '--no-entry',
      '--gc-sections',
      '--strip-all',
      '-z',
      'stack-size=262144',
      '--export=malloc',
      '--export=free',
      '--export=ov_io',
      ...objs,
      '-o',
      wasm,
    ],
    { stdio: 'inherit' },
  );
  return readFileSync(wasm);
}

function emit(name, wasm, s) {
  const packed = deflateRawSync(wasm, { level: 9 });
  const b64 = packed.toString('base64');
  const lines = [];
  for (let i = 0; i < b64.length; i += 120) lines.push(`  '${b64.slice(i, i + 120)}'`);
  const ts =
    `// Generated by wasm/build.mjs — do not edit.\n` +
    `// ${name} ${s.version} (${s.license}, ${s.url}) compiled to wasm32; ${wasm.length} bytes, raw-deflated + base64.\n` +
    `export const WASM_SIZE = ${wasm.length};\n` +
    `export const WASM_DEFLATED_B64 =\n${lines.join(' +\n')};\n`;
  writeFileSync(join(outDir, `${name}-wasm.ts`), ts);
  console.log(`${name}: wasm ${wasm.length} bytes, deflated ${packed.length}, base64 ${b64.length}`);
}

const libc = join(here, 'libc.c');

{
  const root = fetchSource(SOURCES.brotli);
  const c = join(root, 'c');
  const srcs = [libc, join(here, 'brotli_glue.c'), ...cfiles(join(c, 'common')), ...cfiles(join(c, 'enc')), ...cfiles(join(c, 'dec'))];
  emit('brotli', compile('brotli', srcs, [`-I${join(c, 'include')}`]), SOURCES.brotli);
}

{
  const root = fetchSource(SOURCES.zstd);
  const lib = join(root, 'lib');
  const srcs = [
    libc,
    join(here, 'zstd_glue.c'),
    ...cfiles(join(lib, 'common')),
    ...cfiles(join(lib, 'compress')),
    ...cfiles(join(lib, 'decompress')),
  ];
  const defs = ['-DZSTD_DISABLE_ASM', '-DZSTD_TRACE=0', '-DDEBUGLEVEL=0', '-DZSTD_LEGACY_SUPPORT=0', '-DXXH_NO_STDLIB'];
  emit('zstd', compile('zstd', srcs, [`-I${lib}`, `-I${join(lib, 'common')}`, ...defs]), SOURCES.zstd);
}
