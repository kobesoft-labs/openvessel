const FK = [0xa3b1bac6, 0x56aa3350, 0x677d9197, 0xb27022dc];

const rotl = (x: number, n: number) => ((x << n) | (x >>> (32 - n))) >>> 0;
const tau = (a: number) => ((SBOX[a >>> 24] << 24) | (SBOX[(a >>> 16) & 0xff] << 16) | (SBOX[(a >>> 8) & 0xff] << 8) | SBOX[a & 0xff]) >>> 0;
/** T: the round function's linear part L after τ */
const t = (a: number) => {
  const b = tau(a);
  return (b ^ rotl(b, 2) ^ rotl(b, 10) ^ rotl(b, 18) ^ rotl(b, 24)) >>> 0;
};
/** T': the key schedule's L' */
const tk = (a: number) => {
  const b = tau(a);
  return (b ^ rotl(b, 13) ^ rotl(b, 23)) >>> 0;
};

function roundKeys(key: Uint8Array): Uint32Array {
  const k = new Uint32Array(36);
  for (let i = 0; i < 4; i++) k[i] = (((key[4 * i] << 24) | (key[4 * i + 1] << 16) | (key[4 * i + 2] << 8) | key[4 * i + 3]) ^ FK[i]) >>> 0;
  const rk = new Uint32Array(32);
  for (let i = 0; i < 32; i++) {
    // CK_i: bytes (4i + j) * 7 mod 256
    let ck = 0;
    for (let j = 0; j < 4; j++) ck = (ck << 8) | (((4 * i + j) * 7) & 0xff);
    k[i + 4] = (k[i] ^ tk((k[i + 1] ^ k[i + 2] ^ k[i + 3] ^ ck) >>> 0)) >>> 0;
    rk[i] = k[i + 4];
  }
  return rk;
}

function crypt(rk: Uint32Array, decrypt: boolean, src: Uint8Array, so: number, dst: Uint8Array, d: number) {
  const x = new Uint32Array(4);
  for (let i = 0; i < 4; i++) x[i] = (src[so + 4 * i] << 24) | (src[so + 4 * i + 1] << 16) | (src[so + 4 * i + 2] << 8) | src[so + 4 * i + 3];
  let [x0, x1, x2, x3] = x;
  for (let i = 0; i < 32; i++) {
    const r = rk[decrypt ? 31 - i : i];
    const n = (x0 ^ t((x1 ^ x2 ^ x3 ^ r) >>> 0)) >>> 0;
    x0 = x1;
    x1 = x2;
    x2 = x3;
    x3 = n;
  }
  // R: the output is the last four words reversed
  const out = [x3, x2, x1, x0];
  for (let i = 0; i < 4; i++) {
    dst[d + 4 * i] = out[i] >>> 24;
    dst[d + 4 * i + 1] = out[i] >>> 16;
    dst[d + 4 * i + 2] = out[i] >>> 8;
    dst[d + 4 * i + 3] = out[i];
  }
}

export function sm4(key: Uint8Array): BlockCipher {
  const rk = roundKeys(key);
  return {
    blockSize: 16,
    encrypt: (src, so, dst, d) => crypt(rk, false, src, so, dst, d),
    decrypt: (src, so, dst, d) => crypt(rk, true, src, so, dst, d),
  };
}
