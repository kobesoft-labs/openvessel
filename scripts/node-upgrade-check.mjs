// Shows what changes for OpenVessel if it moves to another Node.js release.
//   node scripts/node-upgrade-check.mjs 22.21.0      → docs/node-upgrades/22.20.0-to-22.21.0.md
// Compares the pinned version's data (vendor/node, src/node/data) with a dump of the target
// (same Docker image dumper as gen-node-data.mjs): builtins added/removed/changed, binding
// members added/removed (the C++ surface OpenVessel re-implements), constants and options.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { dumpNode } from './gen-node-data.mjs';

const root = new URL('..', import.meta.url).pathname;
const from = /NODE_VERSION = '([^']+)'/.exec(readFileSync(join(root, 'src/node/version.ts'), 'utf8'))[1];
const to = process.argv[2];
if (!to) {
  console.error('usage: node scripts/node-upgrade-check.mjs <version>');
  process.exit(1);
}

const cur = {
  natives: JSON.parse(readFileSync(join(root, 'vendor/node/natives.json'), 'utf8')),
  bindings: JSON.parse(readFileSync(join(root, 'src/node/data/bindings.json'), 'utf8')),
  proc: JSON.parse(readFileSync(join(root, 'src/node/data/process.json'), 'utf8')),
};
console.log(`dumping node ${to}…`);
const next = dumpNode(to);

const out = [`# Node ${from} → ${to}`, '', `Generated by \`node scripts/node-upgrade-check.mjs ${to}\` on ${new Date().toISOString().slice(0, 10)}.`, ''];

// builtins
const a = new Set(Object.keys(cur.natives));
const b = new Set(Object.keys(next.natives));
const added = [...b].filter((x) => !a.has(x)).sort();
const removed = [...a].filter((x) => !b.has(x)).sort();
const changed = [...a].filter((x) => b.has(x) && cur.natives[x] !== next.natives[x]).sort();
out.push('## Builtins (lib/)', '', `${changed.length} changed, ${added.length} added, ${removed.length} removed.`, '');
if (added.length) out.push('Added:', '', ...added.map((x) => `- \`${x}\``), '');
if (removed.length) out.push('Removed:', '', ...removed.map((x) => `- \`${x}\``), '');
if (changed.length) {
  out.push('Changed (lines − / +):', '');
  for (const id of changed) {
    const l1 = new Set(cur.natives[id].split('\n'));
    const l2 = new Set(next.natives[id].split('\n'));
    const minus = [...l1].filter((l) => !l2.has(l)).length;
    const plus = [...l2].filter((l) => !l1.has(l)).length;
    const touchesBinding = [...l2].some((l) => !l1.has(l) && /internalBinding\(/.test(l));
    out.push(`- \`${id}\` −${minus} +${plus}${touchesBinding ? ' **(binding use changed)**' : ''}`);
  }
  out.push('');
}

// bindings: members and their kinds
const kind = (v) => {
  if (v && typeof v === 'object') {
    if ('__fn' in v) return v.proto ? `class(${v.proto.join(',')})` : 'function';
    if ('__symbol' in v) return 'symbol';
    if ('__typed' in v) return `${v.__typed}(${v.length})`;
    const j = JSON.stringify(v);
    return j.length > 80 ? `object (${j.length} chars, hash ${hash(j)})` : j;
  }
  const j = JSON.stringify(v);
  return typeof v === 'string' && j.length > 80 ? `string (${v.length} chars, hash ${hash(v)})` : j;
};
function hash(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (Math.imul(h, 31) + s.charCodeAt(i)) | 0;
  return (h >>> 0).toString(16);
}
out.push('## Bindings (C++ surface re-implemented in src/nodejs/bindings)', '');
let bindingChanges = 0;
for (const name of [...new Set([...Object.keys(cur.bindings), ...Object.keys(next.bindings)])].sort()) {
  const x = cur.bindings[name] ?? {};
  const y = next.bindings[name] ?? {};
  const lines = [];
  for (const k of [...new Set([...Object.keys(x), ...Object.keys(y)])].sort()) {
    if (k === '__errmap') continue;
    if (!(k in y)) lines.push(`- removed \`${k}\``);
    else if (!(k in x)) lines.push(`- added \`${k}\`: ${kind(y[k])}`);
    else if (kind(x[k]) !== kind(y[k])) lines.push(`- changed \`${k}\`: ${kind(x[k])} → ${kind(y[k])}`);
  }
  if (lines.length) {
    bindingChanges += lines.length;
    out.push(`### ${name}`, '', ...lines, '');
  }
}
if (!bindingChanges) out.push('No changes.', '');

// options
const o1 = new Set(Object.keys(cur.proc.optionValues));
const o2 = new Set(Object.keys(next.proc.optionValues));
const oAdded = [...o2].filter((x) => !o1.has(x));
const oRemoved = [...o1].filter((x) => !o2.has(x));
const oDefault = [...o1].filter((x) => o2.has(x) && JSON.stringify(cur.proc.optionValues[x]) !== JSON.stringify(next.proc.optionValues[x]));
out.push('## CLI options', '');
if (oAdded.length) out.push(`Added: ${oAdded.map((x) => `\`${x}\``).join(', ')}`, '');
if (oRemoved.length) out.push(`Removed: ${oRemoved.map((x) => `\`${x}\``).join(', ')}`, '');
if (oDefault.length) out.push('Default changed:', '', ...oDefault.map((x) => `- \`${x}\`: ${JSON.stringify(cur.proc.optionValues[x])} → ${JSON.stringify(next.proc.optionValues[x])}`), '');
if (!oAdded.length && !oRemoved.length && !oDefault.length) out.push('No changes.', '');

// bundled dependency versions
out.push('## process.versions', '');
for (const k of [...new Set([...Object.keys(cur.proc.versions), ...Object.keys(next.proc.versions)])].sort()) {
  if (cur.proc.versions[k] !== next.proc.versions[k]) out.push(`- ${k}: ${cur.proc.versions[k] ?? '—'} → ${next.proc.versions[k] ?? '—'}`);
}
out.push('');

mkdirSync(join(root, 'docs/node-upgrades'), { recursive: true });
const file = join(root, `docs/node-upgrades/${from}-to-${to}.md`);
writeFileSync(file, out.join('\n'));
console.log(`${changed.length} builtins changed, ${added.length} added, ${removed.length} removed; ${bindingChanges} binding member changes → ${file}`);
