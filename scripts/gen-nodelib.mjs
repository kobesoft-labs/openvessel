// Bundles Node's builtins (vendor/node/natives.json) into dist/runtime/nodelib.js: one ES module
// whose export maps each builtin id to its wrapper function, compiled lazily by V8 and code-cached
// with the worker script. Sources are unchanged except for the replacements in src/nodejs/overrides/.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;

export function genNodeLib(outFile = join(root, 'dist/runtime/nodelib.js')) {
  const natives = JSON.parse(readFileSync(join(root, 'vendor/node/natives.json'), 'utf8'));
  const overridesDir = join(root, 'src/nodejs/overrides');
  const overrides = {};
  const walk = (d) => {
    if (!existsSync(d)) return;
    for (const n of readdirSync(d)) {
      const p = join(d, n);
      if (statSync(p).isDirectory()) walk(p);
      else if (n.endsWith('.js')) overrides[relative(overridesDir, p).replace(/\.js$/, '')] = readFileSync(p, 'utf8');
    }
  };
  walk(overridesDir);
  // not shipped: V8's profiler tools (no --prof in a browser); amaro is replaced by an override
  const skip = (id) => id.startsWith('internal/deps/v8/tools/');
  const params = (id) => {
    if (id.startsWith('internal/per_context/')) return 'exports, primordials, privateSymbols, perIsolateSymbols';
    if (id === 'internal/bootstrap/realm') return 'process, getLinkedBinding, getInternalBinding, primordials';
    if (id.startsWith('internal/bootstrap/') || id.startsWith('internal/main/')) return 'process, require, internalBinding, primordials';
    return 'exports, require, module, process, internalBinding, primordials';
  };
  const ids = Object.keys(natives).sort();
  let out = `// Generated by scripts/gen-nodelib.mjs from Node.js ${JSON.parse(readFileSync(join(root, 'src/node/data/process.json'), 'utf8')).versions.node} — see vendor/node/LICENSE.\n`;
  out += `export const ids = ${JSON.stringify(ids)};\n`;
  out += 'export const fns = {\n';
  for (const id of ids) {
    if (skip(id)) continue;
    const src = overrides[id] ?? natives[id];
    out += `${JSON.stringify(id)}: function (${params(id)}) {${src}\n},\n`;
  }
  out += '};\n';
  mkdirSync(join(outFile, '..'), { recursive: true });
  writeFileSync(outFile, out);
  return { count: ids.length, bytes: out.length, overrides: Object.keys(overrides) };
}

if (import.meta.url === `file://${process.argv[1]}`) console.log(genNodeLib());
