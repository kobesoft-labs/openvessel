// Generates src/shared/node-path.ts from Node.js's lib/path.js (MIT, Joyent and Node contributors).
//   node scripts/vendor-node-path.mjs [path/to/node/lib/path.js]   (default: vendor/node/lib/path.js, the pinned version's)
// Primordials become plain method calls; process.cwd/env and minimatch are wired to OpenVessel.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const src = readFileSync(process.argv[2] ?? root + 'vendor/node/lib/path.js', 'utf8');

const license = src.slice(0, src.indexOf("'use strict';"));
let body = src.slice(src.indexOf('function isPathSeparator('));
body = body.replace(/module\.exports = isWindows \? win32 : posix;\s*$/, 'export { win32, posix };\n');
body = body.replace(/process\.cwd\(\)/g, '__cwd()').replace(/process\.env\[/g, '__env[');

const header = `${license}// Generated by scripts/vendor-node-path.mjs from Node.js lib/path.js. Do not edit by hand.
// @ts-nocheck
/* eslint-disable */

import { __cwd, __env, __glob, validateObject, validateString } from './node-path-support.ts';

const isWindows = false;
const ArrayPrototypeIncludes = (a, v) => a.includes(v);
const ArrayPrototypeJoin = (a, s) => a.join(s);
const ArrayPrototypePush = (a, ...v) => a.push(...v);
const ArrayPrototypeSlice = (a, s, e) => a.slice(s, e);
const FunctionPrototypeBind = (f, t, ...a) => f.bind(t, ...a);
const StringPrototypeCharCodeAt = (s, i) => s.charCodeAt(i);
const StringPrototypeIncludes = (s, v) => s.includes(v);
const StringPrototypeIndexOf = (s, v, i) => s.indexOf(v, i);
const StringPrototypeLastIndexOf = (s, v, i) => (i === undefined ? s.lastIndexOf(v) : s.lastIndexOf(v, i));
const StringPrototypeRepeat = (s, n) => s.repeat(n);
const StringPrototypeReplace = (s, a, b) => s.replace(a, b);
const StringPrototypeSlice = (s, a, b) => s.slice(a, b);
const StringPrototypeSplit = (s, a, n) => s.split(a, n);
const StringPrototypeToLowerCase = (s) => s.toLowerCase();
const StringPrototypeToUpperCase = (s) => s.toUpperCase();
const CHAR_UPPERCASE_A = 65;
const CHAR_LOWERCASE_A = 97;
const CHAR_UPPERCASE_Z = 90;
const CHAR_LOWERCASE_Z = 122;
const CHAR_DOT = 46;
const CHAR_FORWARD_SLASH = 47;
const CHAR_BACKWARD_SLASH = 92;
const CHAR_COLON = 58;
const CHAR_QUESTION_MARK = 63;

`;
body = body.replace(/function glob\(path, pattern, windows\) \{[\s\S]*?\n\}\n/, 'function glob(path, pattern, windows) {\n  validateString(path, \'path\');\n  validateString(pattern, \'pattern\');\n  return __glob(path, pattern, windows);\n}\n');
writeFileSync(root + 'src/shared/node-path.ts', header + body);
console.log('wrote src/shared/node-path.ts');
