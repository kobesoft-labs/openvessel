// Regenerates the column-width table embedded in src/nodejs/bindings/icu.ts from the real Node
// (ICU's East_Asian_Width, general category and emoji properties as node_i18n.cc combines them).
//
//   npx -y node@<version in src/node/version.ts> --expose-internals --no-warnings test/fixtures-gen/icu-width-table.mjs
//
// Per code point the class is w0 * 3 + w1 (+ 9 when it is skipped after a ZWJ with
// expandEmojiSequence = false), where w0 / w1 are its widths with ambiguousAsFullWidth false / true.
// The table is run-length encoded: base-32 delta to the run's first code point + 'A' + class.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const { internalBinding } = require('internal/test/binding');
const icu = internalBinding('icu');

const classOf = (cp) => {
  const s = String.fromCodePoint(cp);
  const w0 = icu.getStringWidth(s, false, true);
  const w1 = icu.getStringWidth(s, true, true);
  const zwj = '‍' + s;
  const skip = icu.getStringWidth(zwj, true, false) !== icu.getStringWidth(zwj, true, true);
  return w0 * 3 + w1 + (skip ? 9 : 0);
};

let table = '';
let prev = -1;
let prevStart = 0;
for (let cp = 0; cp <= 0x10ffff; cp++) {
  const c = classOf(cp);
  if (c === prev) continue;
  table += (cp - prevStart).toString(32) + String.fromCharCode(65 + c);
  prev = c;
  prevStart = cp;
}

const file = new URL('../../src/nodejs/bindings/icu.ts', import.meta.url);
const src = readFileSync(file, 'utf8');
const begin = '// <width-table>\n';
const end = '// </width-table>\n';
const i = src.indexOf(begin);
const j = src.indexOf(end);
if (i < 0 || j < 0) throw new Error('width-table markers not found in icu.ts');
const lines = table.match(/.{1,120}/g).map((l) => `  '${l}' +`);
lines[lines.length - 1] = lines[lines.length - 1].slice(0, -2) + ';';
const block = `// Generated by test/fixtures-gen/icu-width-table.mjs from Node ${process.version} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}).\nconst WIDTH_TABLE =\n${lines.join('\n')}\n`;
writeFileSync(file, src.slice(0, i + begin.length) + block + src.slice(j));
console.log(`width table: ${table.length} chars`);
