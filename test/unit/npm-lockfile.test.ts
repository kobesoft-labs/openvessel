import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseYarnLock } from '../../src/kernel/npm/lockfile.ts';

const hints = (text: string) => {
  const h = new Map<string, Set<string>>();
  parseYarnLock(text, h);
  return Object.fromEntries([...h].map(([k, v]) => [k, [...v]]));
};

test('yarn.lock v1: plain, scoped and aliased patterns', () => {
  const lock = `# yarn lockfile v1


"@babel/core@^7.0.0", "@babel/core@^7.1.0":
  version "7.24.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.24.0.tgz#abc"

is-number@^6.0.0:
  version "6.0.0"

"isnum@npm:is-number@^7.0.0":
  version "7.0.0"
`;
  assert.deepEqual(hints(lock), { '@babel/core': ['7.24.0'], 'is-number': ['6.0.0', '7.0.0'] });
});

test('yarn.lock of Yarn Berry: name@npm:range keys, versions from resolution', () => {
  const lock = `# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 8
  cacheKey: 10c0

"@babel/core@npm:^7.0.0, @babel/core@npm:^7.1.0":
  version: 7.24.0
  resolution: "@babel/core@npm:7.24.0"
  checksum: 10c0/0123456789abcdef
  languageName: node
  linkType: hard

"isnum@npm:is-number@^7.0.0":
  version: 7.0.0
  resolution: "is-number@npm:7.0.0"
  checksum: 10c0/fedcba

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."
  languageName: unknown
  linkType: soft
`;
  assert.deepEqual(hints(lock), { '@babel/core': ['7.24.0'], 'is-number': ['7.0.0'] });
});
